import { chromium, expect } from "@playwright/test";
import { mkdir } from "node:fs/promises";

await mkdir("../.impeccable/review", { recursive: true });
const browser = await chromium.launch({ channel: "chrome", headless: true, args: ["--use-fake-device-for-media-stream", "--use-fake-ui-for-media-stream"] });
const context = await browser.newContext({ ignoreHTTPSErrors: true, viewport: { width: 1440, height: 1000 }, colorScheme: "light", permissions: ["camera", "microphone", "clipboard-read", "clipboard-write"] });
const page = await context.newPage();
const errors = [];
page.on("pageerror", error => errors.push(error.message));
await page.goto(process.env.WISPRSIGHT_TEST_URL ?? "https://localhost:8765");
await expect(page.getByRole("heading", { name: "Dictate", exact: true })).toBeVisible();
await page.getByLabel("Profile name", { exact: true }).fill("Browser smoke test");
await page.getByRole("button", { name: "Create profile", exact: true }).click();
await expect(page.getByRole("heading", { name: "Calibration", exact: true })).toBeVisible();
await page.evaluate(() => {
  const original = navigator.mediaDevices.getUserMedia.bind(navigator.mediaDevices);
  window.wisprsightMediaTest = { original, requests: 0 };
  navigator.mediaDevices.getUserMedia = async constraints => {
    window.wisprsightMediaTest.requests += 1;
    await new Promise(resolve => { window.wisprsightMediaTest.release = resolve; });
    const stream = await original(constraints);
    window.wisprsightMediaTest.stream = stream;
    return stream;
  };
});
await page.getByRole("button", { name: "Record silent take", exact: true }).click();
await expect(page.getByRole("button", { name: "Waiting for camera permission…" })).toBeDisabled();
await expect(page.getByRole("button", { name: "Settings", exact: true })).toBeDisabled();
await page.getByRole("button", { name: "Cancel camera request" }).click();
await page.evaluate(() => window.wisprsightMediaTest.release());
await expect(page.getByRole("button", { name: "Waiting for camera permission…" })).toHaveCount(0);
if (!await page.evaluate(() => window.wisprsightMediaTest.requests === 1 && window.wisprsightMediaTest.stream.getTracks().every(track => track.readyState === "ended"))) throw new Error("Late camera stream was not stopped");
await page.evaluate(() => { navigator.mediaDevices.getUserMedia = window.wisprsightMediaTest.original; });
await page.screenshot({ path: "../.impeccable/review/calibration.png", fullPage: true });
await expect(page.getByRole("button", { name: "Train locally" })).toBeDisabled();
await page.getByRole("button", { name: "Next suggestion" }).click();
await expect(page.getByLabel("Reference sentence", { exact: true })).not.toHaveValue("I would like to write a short message to my friend");
await page.getByRole("button", { name: "Dictate", exact: true }).click();
await page.getByLabel("Editable transcription").fill("A browser interaction check.");
await page.getByRole("button", { name: "Copy text", exact: true }).click();
await expect(page.getByRole("status")).toContainText("Copied to clipboard.");
await page.getByRole("button", { name: "Clear", exact: true }).click();
await expect(page.getByLabel("Editable transcription")).toHaveValue("");
await page.getByRole("button", { name: "Record sentence", exact: true }).click();
await expect(page.getByText("Recording silently", { exact: true })).toBeVisible();
if (await page.locator("video").evaluate(video => video.srcObject.getAudioTracks().length) !== 0) throw new Error("Dictation requested microphone");
await page.getByRole("button", { name: "Discard", exact: true }).click();
await expect(page.getByText("Camera off", { exact: true })).toBeVisible();
await page.screenshot({ path: "../.impeccable/review/desktop.png", fullPage: true });
await page.setViewportSize({ width: 390, height: 1600 });
await page.screenshot({ path: "../.impeccable/review/mobile.png", fullPage: true });
if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw new Error("Mobile horizontal overflow");
await page.setViewportSize({ width: 1280, height: 900 });
await page.emulateMedia({ colorScheme: "dark", reducedMotion: "reduce" });
await page.screenshot({ path: "../.impeccable/review/dark.png", fullPage: false });
await page.getByRole("button", { name: "Settings", exact: true }).click();
await expect(page.getByRole("heading", { name: "Local profiles" })).toBeVisible();
await page.getByLabel("Profile name", { exact: true }).fill("Browser smoke renamed");
await page.getByRole("button", { name: "Save name", exact: true }).click();
await expect(page.getByRole("option", { name: "Browser smoke renamed", exact: true })).toHaveCount(1);
await page.screenshot({ path: "../.impeccable/review/settings.png", fullPage: true });
page.once("dialog", dialog => dialog.accept());
await page.getByRole("button", { name: "Delete profile", exact: true }).click();
await expect(page.getByRole("heading", { name: "Create your first profile" })).toBeVisible();
await expect(page.getByRole("alert")).toHaveCount(0);
if (errors.length) throw new Error(errors.join("\n"));
console.log("PASS: profile creation/deletion, calibration navigation, transcript editing/copy/clear, light/dark/mobile layouts; no page errors. Camera-only recording/discard verified using a synthetic Chrome camera; real camera and microphone remained off.");
await browser.close();
